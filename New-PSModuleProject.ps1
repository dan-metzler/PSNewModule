function New-PSModuleProject {
    <#
    .SYNOPSIS
        Creates a new local PowerShell module project from the PSNewModule template.

    .DESCRIPTION
        Copies the PSNewModule template into a new folder and renames everything for your module:
        source files, manifest (RootModule, new GUID, Author, Description), test entry point,
        docs, and the publish workflow. No GitHub account or git is required.

        What you get in the new folder:
          Source\               Module manifest (.psd1), root module (.psm1), Public\ and Private\ functions
          Tests\Unit\           Pester tests, run by the Full build
          Docs\                 Markdown help, regenerated by the Local build
          template.build.ps1    Build script (-Type Local or -Type Full)
          Install-Requirements.ps1  Installs ModuleBuilder, Pester, InvokeBuild, platyPS
          .github\workflows\    GitHub Actions release workflow (only used once on GitHub)
          README.md             Getting-started steps for your module

        Two sample functions (Get-CatFact, Get-CatFact2) with tests and docs are included so
        the first build has something to compile and test. Replace them with your own code.

        Paste this whole file into a PowerShell session (or load it with Invoke-RestMethod or
        dot-sourcing) to define the function, then call it. When loaded from a clone of the
        template, the local files are used; otherwise the template is downloaded from GitHub.

    .PARAMETER Name
        Name of the new module. Must start with a letter; letters, digits, '.', '_' and '-' allowed.

    .PARAMETER Path
        Parent folder for the new project. Defaults to the current user's Desktop.

    .PARAMETER Author
        Author written to the module manifest. Defaults to the current user name.

    .PARAMETER Description
        Description written to the module manifest.

    .PARAMETER Branch
        Template branch to download when running remotely. Defaults to 'main'.

    .PARAMETER InstallRequirements
        Runs Install-Requirements.ps1 in the new project to install the build dependencies.

    .PARAMETER GitInit
        Initializes a git repository in the new project and creates an initial commit.
        If git has no user.name/user.email configured, the repository is created without a commit.

    .PARAMETER PassThru
        Returns the new project folder as a DirectoryInfo object.

    .EXAMPLE
        New-PSModuleProject -Name MyModule

        After pasting this function into the console, downloads the template and creates
        the project at Desktop\MyModule.

    .EXAMPLE
        Invoke-RestMethod 'https://raw.githubusercontent.com/dan-metzler/PSNewModule/main/New-PSModuleProject.ps1' -UseDefaultCredentials | Invoke-Expression
        New-PSModuleProject -Name MyModule -InstallRequirements -GitInit

        Loads the function straight from GitHub, then creates the project, installs the build
        dependencies, and initializes git (skipped with a warning if git is not installed).

    .EXAMPLE
        .\New-PSModuleProject.ps1 -Name MyModule -Path C:\Code -InstallRequirements -GitInit

        Runs the file directly from a local clone: creates C:\Code\MyModule from the local
        files, installs dependencies, and initializes git.

    .INPUTS
        None.

    .OUTPUTS
        None by default. System.IO.DirectoryInfo (the new project folder) with -PassThru.

    .NOTES
        Requires PowerShell 5.1 or later. Install-Requirements.ps1 needs access to the
        PowerShell Gallery. git is optional; without a version tag the build uses the
        ModuleVersion in Source\<Name>.psd1.

        After creating the project:
          1. cd into the project folder
          2. .\Install-Requirements.ps1                (skip if you used -InstallRequirements)
          3. .\template.build.ps1 -Type Full           compile + run tests to confirm the setup works
          4. Replace the samples with your code:
               Source\Public\Get-CatFact*.ps1     -> Source\Public\Verb-Noun.ps1 (one function per file)
               Tests\Unit\Get-CatFact*.Tests.ps1  -> Tests\Unit\Verb-Noun.Tests.ps1
               Docs\Get-CatFact*.md               delete; the Local build regenerates Docs\
             Helper functions that should not be exported go in Source\Private.
          5. .\template.build.ps1 -Type Local          compile + regenerate Docs\
          6. Import-Module .\Output\<Name>\<Name>.psd1 -Force   to try your commands

    .LINK
        https://github.com/dan-metzler/PSNewModule
    #>
    [CmdletBinding()]
    param(
        [Parameter(Mandatory)]
        [ValidatePattern('^[A-Za-z][A-Za-z0-9._-]*$')]
        [string]$Name,

        [Parameter()]
        [string]$Path = [Environment]::GetFolderPath('Desktop'),

        [Parameter()]
        [string]$Author = $env:USERNAME,

        [Parameter()]
        [string]$Description = "$Name PowerShell module.",

        [Parameter()]
        [string]$Branch = 'main',

        [Parameter()]
        [switch]$InstallRequirements,

        [Parameter()]
        [switch]$GitInit,

        [Parameter()]
        [switch]$PassThru
    )

    $ErrorActionPreference = 'Stop'

    $templateRepo = 'https://github.com/dan-metzler/PSNewModule'
    $templateName = 'NewModule'

    # ============================================================================
    # Step 1: Validate Destination
    # ============================================================================

    if (-not (Test-Path -Path $Path -PathType Container)) {
        throw "Parent folder '$Path' does not exist."
    }

    $destination = Join-Path -Path (Resolve-Path -Path $Path).ProviderPath -ChildPath $Name

    if ((Test-Path -Path $destination) -and (Get-ChildItem -Path $destination -Force | Select-Object -First 1)) {
        throw "Destination '$destination' already exists and is not empty."
    }

    # ============================================================================
    # Step 2: Copy Template Files
    # ============================================================================
    # Uses the local clone when this file is loaded from one; otherwise downloads
    # the template zip from GitHub. Git-ignored and repo-only items are skipped.

    # README.md documents the template itself; the project gets its own in Step 5.
    $excluded = @('.git', 'Output', 'Dev', 'Development', 'CLAUDE.md', 'README.md', 'New-PSModuleProject.ps1')
    $tempDir = $null

    try {
        if ($PSScriptRoot -and (Test-Path -Path (Join-Path -Path $PSScriptRoot -ChildPath "Source\$templateName.psd1"))) {
            Write-Host "Using local template at $PSScriptRoot"
            $templateRoot = $PSScriptRoot
        }
        else {
            # Windows PowerShell 5.1 may default to TLS 1.0, which GitHub rejects.
            [Net.ServicePointManager]::SecurityProtocol = [Net.ServicePointManager]::SecurityProtocol -bor [Net.SecurityProtocolType]::Tls12

            $tempDir = Join-Path -Path ([IO.Path]::GetTempPath()) -ChildPath ([guid]::NewGuid().ToString())
            New-Item -Path $tempDir -ItemType Directory | Out-Null

            $zipUri = "$templateRepo/archive/refs/heads/$Branch.zip"
            $zipPath = Join-Path -Path $tempDir -ChildPath 'template.zip'
            Write-Host "Downloading template from $zipUri"
            Invoke-WebRequest -Uri $zipUri -OutFile $zipPath -UseBasicParsing -UseDefaultCredentials
            Expand-Archive -Path $zipPath -DestinationPath $tempDir

            # GitHub zips contain a single top-level folder, e.g. PSNewModule-main
            $templateRoot = (Get-ChildItem -Path $tempDir -Directory | Select-Object -First 1).FullName
        }

        New-Item -Path $destination -ItemType Directory -Force | Out-Null
        Get-ChildItem -Path $templateRoot -Force |
            Where-Object { $excluded -notcontains $_.Name } |
            Copy-Item -Destination $destination -Recurse -Force
    }
    finally {
        if ($tempDir) { Remove-Item -Path $tempDir -Recurse -Force -ErrorAction SilentlyContinue }
    }

    # Files from a browser-downloaded zip carry Mark-of-the-Web, which Copy-Item keeps.
    # Under a RemoteSigned execution policy that blocks the build scripts from running.
    if (Get-Command -Name Unblock-File -ErrorAction SilentlyContinue) {
        Get-ChildItem -Path $destination -Recurse -File -Force | Unblock-File
    }

    # ============================================================================
    # Step 3: Rename Template Files
    # ============================================================================

    foreach ($file in @("Source\$templateName.psd1", "Source\$templateName.psm1", "Tests\$templateName.Tests.ps1")) {
        $filePath = Join-Path -Path $destination -ChildPath $file
        if (Test-Path -Path $filePath) {
            Rename-Item -Path $filePath -NewName ((Split-Path -Path $filePath -Leaf) -replace "^$templateName", $Name)
        }
    }

    # ============================================================================
    # Step 4: Replace Placeholders
    # ============================================================================
    # Swaps the template module name in code, workflow, and docs files.

    $utf8NoBom = New-Object -TypeName System.Text.UTF8Encoding -ArgumentList $false

    function Update-FileContent {
        param([string]$FilePath, [scriptblock]$Transform)
        $content = [IO.File]::ReadAllText($FilePath)
        $updated = & $Transform $content
        if ($updated -cne $content) { [IO.File]::WriteAllText($FilePath, $updated, $utf8NoBom) }
    }

    Get-ChildItem -Path $destination -Recurse -File -Include '*.ps1', '*.psd1', '*.psm1', '*.yml', '*.md' |
        ForEach-Object {
            Update-FileContent -FilePath $_.FullName -Transform {
                param($text)
                $text.Replace($templateName, $Name).Replace('YOUR_MODULE_NAME', $Name)
            }
        }

    # Manifest metadata. Single quotes are doubled to stay valid inside '...' strings.
    $manifestPath = Join-Path -Path $destination -ChildPath "Source\$Name.psd1"
    Update-FileContent -FilePath $manifestPath -Transform {
        param($text)
        $safeAuthor = $Author.Replace("'", "''")
        $safeDescription = $Description.Replace("'", "''")
        $text = $text -replace "(?m)^(\s*GUID\s*=\s*)'[^']*'", "`$1'$([guid]::NewGuid())'"
        $text = $text -replace "(?m)^(\s*Author\s*=\s*)'[^']*'", "`$1'$safeAuthor'"
        $text = $text -replace "(?m)^(\s*Copyright\s*=\s*)'[^']*'", "`$1'(c) $((Get-Date).Year) $safeAuthor. All rights reserved.'"
        $text -replace "(?m)^(\s*Description\s*=\s*)'[^']*'", "`$1'$safeDescription'"
    }

    # ============================================================================
    # Step 5: Write Project README
    # ============================================================================
    # Single-quoted so markdown backticks are not treated as escape characters.

    $readme = @'
# {{NAME}}

{{DESCRIPTION}}

Created from the [PSNewModule](https://github.com/dan-metzler/PSNewModule) template. Requires PowerShell 5.1 or later.

## Getting started

```powershell
.\Install-Requirements.ps1          # once; installs ModuleBuilder, Pester, InvokeBuild, platyPS from the PowerShell Gallery
.\template.build.ps1 -Type Full     # compile + run tests to confirm the setup works
```

Then replace the sample functions with your own:

| Sample | Replace with |
|---|---|
| `Source/Public/Get-CatFact*.ps1` | `Source/Public/Verb-Noun.ps1`, one function per file, file name = function name |
| `Tests/Unit/Get-CatFact*.Tests.ps1` | `Tests/Unit/Verb-Noun.Tests.ps1` |
| `Docs/Get-CatFact*.md` | Delete; the Local build regenerates `Docs/` |

Functions in `Source/Public` are exported. Helpers that should stay internal go in `Source/Private`.

## Build and try it

```powershell
.\template.build.ps1 -Type Local    # compile, import, regenerate Docs/
.\template.build.ps1 -Type Full     # compile, import, run Pester tests
Import-Module .\Output\{{NAME}}\{{NAME}}.psd1 -Force
```

The built module goes to `Output/{{NAME}}` and is what the tests run against. The version comes from the latest git tag (`v1.2.3`) if there is one, otherwise from `ModuleVersion` in `Source/{{NAME}}.psd1`.

## Folder layout

| Path | Contents |
|---|---|
| `Source/` | Module source: `.psd1`, `.psm1`, `Public/` (exported), `Private/` (internal) |
| `Tests/Unit/` | Pester tests (`*.Tests.ps1`) |
| `Docs/` | Generated markdown help, one file per exported function |
| `Output/` | Built module (not committed) |

## Publishing

To put this project on GitHub and release versions through the included workflow, see [Moving a local project to GitHub](https://github.com/dan-metzler/PSNewModule#moving-a-local-project-to-github) and [Publishing](https://github.com/dan-metzler/PSNewModule#publishing) in the template README.
'@
    $readme = $readme.Replace('{{NAME}}', $Name).Replace('{{DESCRIPTION}}', $Description)
    [IO.File]::WriteAllText((Join-Path -Path $destination -ChildPath 'README.md'), $readme, $utf8NoBom)

    Write-Host "Created module project '$Name' at $destination" -ForegroundColor Green

    # ============================================================================
    # Step 6: Optional Setup
    # ============================================================================

    if ($InstallRequirements) {
        Write-Host 'Installing build dependencies...'
        & (Join-Path -Path $destination -ChildPath 'Install-Requirements.ps1')
    }

    if ($GitInit) {
        if (-not (Get-Command -Name git -ErrorAction SilentlyContinue)) {
            Write-Warning 'git was not found on PATH; skipping repository initialization.'
        }
        else {
            # Windows PowerShell 5.1 turns redirected native stderr into terminating errors
            # under 'Stop', so git runs with 'Continue' and is checked via $LASTEXITCODE.
            $previousPreference = $ErrorActionPreference
            $ErrorActionPreference = 'Continue'
            try {
                # --initial-branch needs git 2.28+; older git gets a plain init, then HEAD is pointed at main.
                git -C $destination init --initial-branch=main --quiet 2>$null
                if ($LASTEXITCODE -ne 0) {
                    git -C $destination init --quiet 2>$null
                    if ($LASTEXITCODE -eq 0) { git -C $destination symbolic-ref HEAD refs/heads/main 2>$null }
                }

                # Only continue once the new folder has its own .git; otherwise git add would
                # stage the files into an enclosing repository, if there is one.
                $repoCreated = Test-Path -Path (Join-Path -Path $destination -ChildPath '.git')
                if ($repoCreated) {
                    git -C $destination -c core.safecrlf=false add --all 2>$null
                    $gitEmail = git -C $destination config user.email
                    $gitUser = git -C $destination config user.name
                }
            }
            finally {
                $ErrorActionPreference = $previousPreference
            }

            # Without an identity git refuses to commit; say how to fix it instead of failing.
            if (-not $repoCreated) {
                Write-Warning 'git init failed; skipping repository initialization. Run git init in the project folder manually.'
            }
            elseif ($gitEmail -and $gitUser) {
                git -C $destination commit --quiet -m '[chore] initial project from PSNewModule template'
                if ($LASTEXITCODE -ne 0) {
                    Write-Warning 'git commit failed. Files are staged; commit them manually.'
                }
            }
            else {
                Write-Warning ("git repository created, but no initial commit: git user.name/user.email is not set.`n" +
                    "  git config --global user.name  'Your Name'`n" +
                    "  git config --global user.email 'you@example.com'`n" +
                    "  git -C '$destination' commit -m '[chore] initial commit'")
            }
        }
    }

    # ============================================================================
    # Step 7: Next Steps
    # ============================================================================

    $step = 0
    Write-Host ''
    Write-Host 'Next steps' -ForegroundColor Cyan
    Write-Host "  $((++$step)). cd '$destination'"
    if (-not $InstallRequirements) {
        Write-Host "  $((++$step)). .\Install-Requirements.ps1            # once; needs PowerShell Gallery access"
    }
    Write-Host "  $((++$step)). .\template.build.ps1 -Type Full       # compile + run tests to confirm the setup works"
    Write-Host "  $((++$step)). Replace the samples with your code:"
    Write-Host '       Source\Public\Get-CatFact*.ps1     -> Source\Public\Verb-Noun.ps1 (one function per file)'
    Write-Host '       Tests\Unit\Get-CatFact*.Tests.ps1  -> Tests\Unit\Verb-Noun.Tests.ps1'
    Write-Host '       Docs\Get-CatFact*.md               delete; the Local build regenerates Docs\'
    Write-Host '     Helper functions that should not be exported go in Source\Private.'
    Write-Host "  $((++$step)). .\template.build.ps1 -Type Local      # compile + regenerate Docs\"
    Write-Host "  $((++$step)). Import-Module .\Output\$Name\$Name.psd1 -Force"
    Write-Host ''
    Write-Host "Version: ModuleVersion in Source\$Name.psd1, or a git tag like v1.0.0."
    Write-Host 'These steps are also in the project README.md.'

    if ($PassThru) { Get-Item -Path $destination }
}

# When the file is run directly (.\New-PSModuleProject.ps1 -Name X) rather than
# pasted, piped to Invoke-Expression, or dot-sourced, forward the arguments.
if ($MyInvocation.InvocationName -ne '.' -and $MyInvocation.MyCommand.Path) {
    New-PSModuleProject @args
}
